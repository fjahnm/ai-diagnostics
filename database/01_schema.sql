BEGIN;

CREATE TABLE IF NOT EXISTS projects (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  slug VARCHAR(80) NOT NULL UNIQUE,
  name VARCHAR(140) NOT NULL,
  description VARCHAR(300),
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT ck_projects_slug CHECK (slug ~ '^[a-z0-9][a-z0-9-]{1,79}$')
);

CREATE TABLE IF NOT EXISTS services (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  project_id INTEGER NOT NULL REFERENCES projects(id) ON DELETE RESTRICT,
  code VARCHAR(80) NOT NULL,
  name VARCHAR(140) NOT NULL,
  type VARCHAR(32) NOT NULL,
  enabled BOOLEAN NOT NULL DEFAULT TRUE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT uq_services_project_code UNIQUE (project_id, code),
  CONSTRAINT ck_services_type CHECK (type IN ('REST_API', 'INTEGRATION', 'BACKGROUND_JOB')),
  CONSTRAINT ck_services_code CHECK (code ~ '^[a-z0-9][a-z0-9-]{1,79}$')
);

CREATE TABLE IF NOT EXISTS diagnostic_events (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  service_id INTEGER NOT NULL REFERENCES services(id) ON DELETE RESTRICT,
  event_uid VARCHAR(96) NOT NULL DEFAULT gen_random_uuid()::text,
  observed_at TIMESTAMPTZ NOT NULL,
  level VARCHAR(12) NOT NULL DEFAULT 'INFO',
  success BOOLEAN NOT NULL,
  http_status SMALLINT,
  duration_ms INTEGER NOT NULL,
  error_code VARCHAR(70),
  message VARCHAR(280),
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT uq_diagnostic_events_uid UNIQUE (service_id, event_uid),
  CONSTRAINT ck_events_level CHECK (level IN ('INFO', 'WARN', 'ERROR')),
  CONSTRAINT ck_events_status CHECK (http_status IS NULL OR http_status BETWEEN 100 AND 599),
  CONSTRAINT ck_events_duration CHECK (duration_ms BETWEEN 0 AND 600000)
);

CREATE TABLE IF NOT EXISTS ai_analyses (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  service_id INTEGER NOT NULL REFERENCES services(id) ON DELETE RESTRICT,
  provider VARCHAR(20) NOT NULL,
  model VARCHAR(110) NOT NULL,
  status VARCHAR(12) NOT NULL,
  period_days SMALLINT NOT NULL,
  metrics_snapshot JSONB NOT NULL,
  evidences_snapshot JSONB NOT NULL,
  result JSONB,
  error_code VARCHAR(64),
  duration_ms INTEGER,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  finished_at TIMESTAMPTZ,
  CONSTRAINT ck_analyses_status CHECK (status IN ('pending','completed','failed')),
  CONSTRAINT ck_analyses_days CHECK (period_days IN (7,14,30)),
  CONSTRAINT ck_analyses_duration CHECK (duration_ms IS NULL OR duration_ms >= 0)
);

CREATE INDEX IF NOT EXISTS ix_services_project ON services(project_id);
CREATE INDEX IF NOT EXISTS ix_events_service_time ON diagnostic_events(service_id, observed_at DESC);
CREATE INDEX IF NOT EXISTS ix_events_failures ON diagnostic_events(service_id, observed_at DESC) WHERE success = FALSE;
CREATE INDEX IF NOT EXISTS ix_analyses_service_time ON ai_analyses(service_id, created_at DESC);
CREATE INDEX IF NOT EXISTS ix_analyses_time ON ai_analyses(created_at DESC);

COMMENT ON TABLE diagnostic_events IS 'Normalized, non-sensitive events; external production logs must never be imported without authorization.';
COMMENT ON COLUMN ai_analyses.metrics_snapshot IS 'Backend-calculated metrics used for a specific LLM request.';
COMMENT ON COLUMN ai_analyses.evidences_snapshot IS 'Deterministic evidence IDs and descriptions verified independently from the model.';

COMMIT;
