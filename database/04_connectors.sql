BEGIN;

CREATE TABLE IF NOT EXISTS connectors (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  service_id INTEGER NOT NULL REFERENCES services(id) ON DELETE RESTRICT,
  name VARCHAR(120) NOT NULL,
  endpoint_url TEXT NOT NULL,
  mode VARCHAR(12) NOT NULL DEFAULT 'JSON_LOGS',
  records_path VARCHAR(160) NOT NULL DEFAULT 'items',
  field_mapping JSONB NOT NULL,
  auth_type VARCHAR(12) NOT NULL DEFAULT 'NONE',
  auth_header VARCHAR(64),
  encrypted_secret TEXT,
  pagination_mode VARCHAR(8) NOT NULL DEFAULT 'NONE',
  page_parameter VARCHAR(48) NOT NULL DEFAULT 'page',
  page_start SMALLINT NOT NULL DEFAULT 1,
  max_pages SMALLINT NOT NULL DEFAULT 1,
  page_size_parameter VARCHAR(48),
  page_size SMALLINT NOT NULL DEFAULT 100,
  enabled BOOLEAN NOT NULL DEFAULT TRUE,
  last_success_at TIMESTAMPTZ,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT uq_connectors_service_name UNIQUE (service_id, name),
  CONSTRAINT ck_connectors_mode CHECK (mode IN ('JSON_LOGS','HTTP_CHECK')),
  CONSTRAINT ck_connectors_auth CHECK (auth_type IN ('NONE', 'BEARER', 'API_KEY')),
  CONSTRAINT ck_connectors_pagination CHECK (pagination_mode IN ('NONE', 'PAGE')),
  CONSTRAINT ck_connectors_page_start CHECK (page_start BETWEEN 0 AND 1000),
  CONSTRAINT ck_connectors_max_pages CHECK (max_pages BETWEEN 1 AND 5),
  CONSTRAINT ck_connectors_page_size CHECK (page_size BETWEEN 1 AND 200),
  CONSTRAINT ck_connectors_mapping CHECK (jsonb_typeof(field_mapping) = 'object')
);

CREATE TABLE IF NOT EXISTS connector_sync_runs (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  connector_id INTEGER NOT NULL REFERENCES connectors(id) ON DELETE RESTRICT,
  status VARCHAR(12) NOT NULL,
  received INTEGER NOT NULL DEFAULT 0,
  inserted INTEGER NOT NULL DEFAULT 0,
  duplicates INTEGER NOT NULL DEFAULT 0,
  skipped INTEGER NOT NULL DEFAULT 0,
  error_code VARCHAR(60),
  started_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  finished_at TIMESTAMPTZ,
  CONSTRAINT ck_sync_status CHECK (status IN ('running', 'completed', 'failed')),
  CONSTRAINT ck_sync_counts CHECK (received >= 0 AND inserted >= 0 AND duplicates >= 0 AND skipped >= 0)
);

CREATE INDEX IF NOT EXISTS ix_connectors_service ON connectors(service_id);
CREATE INDEX IF NOT EXISTS ix_connector_sync_runs_history ON connector_sync_runs(connector_id, started_at DESC);

COMMENT ON TABLE connectors IS 'Configuration-driven, read-only HTTP JSON connectors. Credentials encrypted at rest.';
COMMENT ON TABLE connector_sync_runs IS 'Audit of manual connector sync executions; no external payloads or secrets stored.';
COMMIT;
